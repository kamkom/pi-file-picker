// Regenerates src/icon-table.ts from scripts/icon-spec.mjs.
//
//   curl -sSLo /tmp/glyphnames.json https://raw.githubusercontent.com/ryanoasis/nerd-fonts/master/glyphnames.json
//   node scripts/generate-icons.mjs /tmp/glyphnames.json
//
// Every Nerd Font name is resolved against the official glyph table, so a typo fails loudly
// instead of shipping a tofu box.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as spec from "./icon-spec.mjs";

const glyphPath = process.argv[2];
if (!glyphPath) {
	console.error("usage: node scripts/generate-icons.mjs <glyphnames.json>");
	process.exit(1);
}

const glyphs = JSON.parse(readFileSync(glyphPath, "utf8"));
const missing = [];

function entry([name, color, emoji]) {
	const glyph = glyphs[name];
	if (!glyph) {
		missing.push(name);
		return "null";
	}
	if (!/^#[0-9a-f]{6}$/i.test(color)) {
		missing.push(`${name} (bad color ${color})`);
	}
	const nerd = `\\u{${glyph.code}}`;
	return `{ nerd: "${nerd}", color: "${color}"${emoji ? `, emoji: "${emoji}"` : ""} }, // nf-${name}`;
}

function table(name, record) {
	const rows = Object.entries(record).map(([key, value]) => `\t${JSON.stringify(key)}: ${entry(value)}`);
	return `export const ${name}: Readonly<Record<string, IconSpec>> = {\n${rows.join("\n")}\n};\n`;
}

const out = `// Generated by scripts/generate-icons.mjs from scripts/icon-spec.mjs. Do not edit by hand.
// Nerd Fonts glyph table version: ${glyphs.METADATA?.version ?? "unknown"}

export interface IconSpec {
	/** Nerd Font v3 glyph. */
	nerd: string;
	/** Brand/type color as #rrggbb, tuned for dark backgrounds. */
	color: string;
	/** Emoji fallback for terminals without a Nerd Font. */
	emoji?: string;
}

export const DEFAULT_FILE: IconSpec = ${entry(spec.DEFAULT_FILE).replace(/, \/\/.*$/, ";")}
export const DEFAULT_FOLDER: IconSpec = ${entry(spec.DEFAULT_FOLDER).replace(/, \/\/.*$/, ";")}
export const OPEN_FOLDER: IconSpec = ${entry(spec.OPEN_FOLDER).replace(/, \/\/.*$/, ";")}

${table("FILE_NAMES", spec.FILE_NAMES)}
${table("FILE_PREFIXES", spec.FILE_PREFIXES)}
${table("FILE_SUFFIXES", spec.FILE_SUFFIXES)}
${table("EXTENSIONS", spec.EXTENSIONS)}
${table("FOLDER_NAMES", spec.FOLDER_NAMES)}`;

if (missing.length > 0) {
	console.error(`Unknown Nerd Font glyph names:\n  ${missing.join("\n  ")}`);
	process.exit(1);
}

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "icon-table.ts");
writeFileSync(target, out);
console.log(`wrote ${target}`);
